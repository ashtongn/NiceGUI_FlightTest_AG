"""
Replay real channelizer decode buffers (test_dump_replay.py)
============================================================
Loads the XCVDUMP .npy buffers pulled from the G40 (the exact baseband the
decode pool saw over the single-card dual-FDD RF path) and runs
decode_pool._default_decode with the same DecodeSpec the worker built.

This closes the gap test_rf_decode_replay.py can't: that harness synthesizes
the channel baseband; this one uses the GPU channelizer's actual output, so a
demod bug that only shows against the real channel filter/LO-leak/CFO
reproduces on the desk.

Usage:  python3 test_dump_replay.py [MOD ...]        # default: all in xcv_dumps/
        add --verbose for per-buffer demod internals
"""
from __future__ import annotations

import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np

from dpmg.dsp.decode_pool import DecodeSpec, _default_decode

DUMP_DIR = "xcv_dumps"

# dump-name mod: dsweep plan file (plan carries the demod params + frame)
PLAN_FOR = {
    "4FSK": "dsweep_4FSK_plan.json",
    "PI4-QPSK": "dsweep_pi4-QPSK_plan.json",
    "DQPSK": "dsweep_DQPSK_plan.json",
    "OQPSK": "dsweep_OQPSK_plan.json",
    "DSSS": "dsweep_DSSS_plan.json",
    "CSS": "dsweep_CSS_plan.json",
    "FSK": "dsweep_FSK_plan.json",
}


def spec_from_plan(mod: str, fs_out: float, sps: float) -> DecodeSpec:
    entry = json.load(open(PLAN_FOR[mod]))["entries"][0]
    params = dict(entry.get("params") or {})
    params["frame"] = entry.get("frame") or {}
    return DecodeSpec(modulation=entry["modulation"], fs_out=fs_out, sps=sps,
                      demod_params=params, lock={})


def main() -> int:
    only = [a for a in sys.argv[1:] if not a.startswith("-")]
    bufs = sorted(glob.glob(os.path.join(DUMP_DIR, "xcv_buf_*.npy")))
    if not bufs:
        # This is a desk-debug replay harness, not a portable unit test: the .npy
        # buffers are git-ignored G40 captures, absent on a fresh clone. With
        # nothing to replay there is nothing to verify: SKIP (0), not FAIL.
        print(f"SKIP: no capture dumps in {DUMP_DIR}/ (needs real G40 .npy buffers)")
        return 0
    results = {}
    for bf in bufs:
        m = re.match(r"xcv_buf_(.+)_(\d+)\.npy", os.path.basename(bf))
        if not m:
            continue
        mod, idx = m.group(1), int(m.group(2))
        if only and mod not in only:
            continue
        if mod not in PLAN_FOR:
            print(f"  {mod}: no plan mapping, skipped"); continue
        if not os.path.exists(PLAN_FOR[mod]):
            # plan carries the demod params; it's regenerated by bench_dualsweep and
            # is git-ignored. Absent: skip this mod rather than crash.
            print(f"  {mod}: plan {PLAN_FOR[mod]} absent (run bench_dualsweep), skipped")
            continue
        bb = np.load(bf)
        meta_f = bf.replace("xcv_buf_", "xcv_meta_")
        if os.path.exists(meta_f):
            fs_out, sps, _n = np.load(meta_f)
        else:
            fs_out, sps = 48000.0, 10.0        # channelizer defaults (gate fs)
        spec = spec_from_plan(mod, float(fs_out), float(sps))
        r = _default_decode(0, bb, spec)
        msgs = getattr(r, "messages", None) or ([r.message] if r.valid else [])
        ok = r.valid and any("PING" in m for m in msgs)
        results.setdefault(mod, []).append(ok)
        print(f"  {mod} #{idx}: len={len(bb)} fs={fs_out:.0f} sps={sps:.3f} "
              f"valid={r.valid} msgs={msgs!r}")
    print("\n===== DUMP REPLAY =====")
    if not results:
        print("  SKIP: dumps present but no plan files to replay against")
        return 0
    fails = 0
    for mod, oks in sorted(results.items()):
        n_ok = sum(oks)
        verdict = "DECODES" if n_ok else "FAILS"
        if not n_ok:
            fails += 1
        print(f"  {mod:10s} {n_ok}/{len(oks)} buffers -> {verdict}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
